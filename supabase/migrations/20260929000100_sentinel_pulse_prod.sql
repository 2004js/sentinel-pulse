-- SENTINEL PULSE production database contract for SIH 2026 PS 26186.
-- Apply through the Supabase SQL editor or Supabase CLI before enabling production mode.

create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('officer','commander','personnel')),
  display_name text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.welfare_cases (
  id uuid primary key default gen_random_uuid(),
  case_id text unique not null,
  personnel_user_id uuid references auth.users(id) on delete set null,
  personnel_token_hash text not null,
  risk_score integer not null check (risk_score between 0 and 100),
  risk_tier text not null check (risk_tier in ('STABLE','WATCH','INTERVENTION','URGENT')),
  trajectory text,
  priority text not null default 'MEDIUM',
  primary_factors jsonb not null default '[]'::jsonb,
  status text not null default 'OPEN',
  recommendation text not null,
  officer_decision text,
  intervention jsonb,
  follow_up_date date,
  personnel_context_ciphertext text,
  model_json jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.alerts (
  id uuid primary key default gen_random_uuid(),
  case_id text not null references public.welfare_cases(case_id) on delete cascade,
  severity text not null,
  title text not null,
  detail text not null,
  status text not null default 'OPEN' check (status in ('OPEN','ACKNOWLEDGED','CLOSED')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.interventions (
  id uuid primary key default gen_random_uuid(),
  case_id text not null references public.welfare_cases(case_id) on delete cascade,
  intervention_type text not null,
  notes text not null default '',
  follow_up_date date,
  outcome text,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);

create table if not exists public.consents (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  consent_type text not null check (consent_type in ('self','hr','wellness','biometric')),
  granted boolean not null,
  updated_at timestamptz not null default now(),
  unique(user_id, consent_type)
);

create table if not exists public.audit_events (
  id bigint generated by default as identity primary key,
  ts timestamptz not null default now(),
  actor_user_id uuid references auth.users(id) on delete set null,
  role text not null,
  subject_hash text,
  event text not null,
  outcome jsonb not null default '{}'::jsonb
);

create table if not exists public.secure_records (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  subject_hash text not null,
  role text not null,
  record_type text not null,
  ciphertext text not null
);

create index if not exists welfare_cases_personnel_user_id_idx on public.welfare_cases(personnel_user_id);
create index if not exists welfare_cases_risk_tier_idx on public.welfare_cases(risk_tier);
create index if not exists welfare_cases_status_idx on public.welfare_cases(status);
create index if not exists alerts_status_idx on public.alerts(status);
create index if not exists alerts_case_id_idx on public.alerts(case_id);
create index if not exists consents_user_id_idx on public.consents(user_id);
create index if not exists audit_events_ts_idx on public.audit_events(ts desc);

-- Role helper: reads only the caller's server-assigned role.
create or replace function public.has_role(expected_role text)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.user_roles
    where user_id = (select auth.uid())
      and role = expected_role
      and active = true
  );
$$;

revoke execute on function public.has_role(text) from public;
grant execute on function public.has_role(text) to authenticated;

-- RLS is defense-in-depth. Backend service connections remain responsible for application workflow authorization.
alter table public.user_roles enable row level security;
alter table public.welfare_cases enable row level security;
alter table public.alerts enable row level security;
alter table public.interventions enable row level security;
alter table public.consents enable row level security;
alter table public.audit_events enable row level security;
alter table public.secure_records enable row level security;

revoke all on public.user_roles, public.welfare_cases, public.alerts, public.interventions, public.consents, public.audit_events, public.secure_records from anon, authenticated;

grant select on public.user_roles to authenticated;
grant select, update on public.welfare_cases to authenticated;
grant select, update on public.alerts to authenticated;
grant select, insert on public.interventions to authenticated;
grant select, insert, update on public.consents to authenticated;
grant select on public.audit_events to authenticated;

-- user_roles: users can read only their own role; role assignment is an administrative operation.
drop policy if exists user_roles_self_select on public.user_roles;
create policy user_roles_self_select on public.user_roles
  for select to authenticated
  using ((select auth.uid()) = user_id);

-- welfare cases: officers see operational welfare cases; personnel see only cases explicitly tied to them.
drop policy if exists welfare_cases_officer_select on public.welfare_cases;
create policy welfare_cases_officer_select on public.welfare_cases
  for select to authenticated
  using ((select public.has_role('officer')));

drop policy if exists welfare_cases_officer_update on public.welfare_cases;
create policy welfare_cases_officer_update on public.welfare_cases
  for update to authenticated
  using ((select public.has_role('officer')))
  with check ((select public.has_role('officer')));

drop policy if exists welfare_cases_personnel_select on public.welfare_cases;
create policy welfare_cases_personnel_select on public.welfare_cases
  for select to authenticated
  using ((select auth.uid()) = personnel_user_id and (select public.has_role('personnel')));

-- Alerts and intervention records are restricted to welfare officers.
drop policy if exists alerts_officer_select on public.alerts;
create policy alerts_officer_select on public.alerts
  for select to authenticated
  using ((select public.has_role('officer')));

drop policy if exists alerts_officer_update on public.alerts;
create policy alerts_officer_update on public.alerts
  for update to authenticated
  using ((select public.has_role('officer')))
  with check ((select public.has_role('officer')));

drop policy if exists interventions_officer_select on public.interventions;
create policy interventions_officer_select on public.interventions
  for select to authenticated
  using ((select public.has_role('officer')));

drop policy if exists interventions_officer_insert on public.interventions;
create policy interventions_officer_insert on public.interventions
  for insert to authenticated
  with check ((select public.has_role('officer')));

-- Personnel consent is private to the owning user.
drop policy if exists consents_self_select on public.consents;
create policy consents_self_select on public.consents
  for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists consents_self_insert on public.consents;
create policy consents_self_insert on public.consents
  for insert to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists consents_self_update on public.consents;
create policy consents_self_update on public.consents
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

-- Audit and encrypted raw records are not directly writable from the browser.
drop policy if exists audit_officer_select on public.audit_events;
create policy audit_officer_select on public.audit_events
  for select to authenticated
  using ((select public.has_role('officer')));

